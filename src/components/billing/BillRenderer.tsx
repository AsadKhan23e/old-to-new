import React, { Fragment } from 'react';
import { BillDesignSettings, Transaction, Customer, getIsPremium } from "@/lib/data-layer";
import { Camera } from "lucide-react";
import Image from "next/image";

type BillRendererProps = {
    bill: Transaction;
    settings: BillDesignSettings;
    customer?: Customer;
    runningBalance?: number;
    onViewImage?: (image: string) => void;
};

import { formatAppDateTime, formatAppDate, formatAppTime } from '@/lib/date-utils';

const formatDateTime = (dateString: string) => {
    return formatAppDateTime(dateString);
};

const formatPaymentDateTime = (dateString: string) => {
    if (!dateString) return 'N/A';
    return `${formatAppDate(dateString)} at ${formatAppTime(dateString, { second: undefined })}`;
};

import { InvoiceBackgroundLayer } from "./InvoiceBackgroundLayer";

export const BillRenderer = ({ bill, settings, customer, runningBalance, onViewImage }: BillRendererProps) => {
    const isPurchase = bill.type === 'purchase';
    const totalPaid = (bill.amountPaid || 0) + (bill.additionalPayments?.reduce((sum, p) => sum + p.amount, 0) || 0);
    const finalBalance = runningBalance !== undefined ? runningBalance : bill.remainingBalance;

    // LEGACY RENDERER (Exactly as per User preference: Image 1 look with Payments)
    const partyLabel = isPurchase ? 'Supplier' : 'Customer';
    return (
        <div className="relative bg-white min-h-[400px] overflow-hidden">
            {/* Background Banner Layer */}
            {settings.backgroundBanner && <InvoiceBackgroundLayer settings={settings} />}

            <div className={`relative z-10 p-6 ${settings.backgroundBanner ? 'bg-white/70 backdrop-blur-[1px]' : 'bg-white'} text-black font-sans text-sm`}>
                <header className="text-center mb-6">
                    {settings.logo && (
                        <div className="mb-2">
                            <img src={settings.logo} alt="Shop Logo" className="mx-auto h-16 w-16 rounded-full object-cover border" />
                        </div>
                    )}
                    <h1 className="text-2xl font-bold mb-1 text-[#6B7A50]">{settings.shopName}</h1>
                    <p className="text-xs text-muted-foreground">{settings.address}</p>
                    <div className="text-xs mt-1 text-muted-foreground">
                        {settings.contacts.map(c => <span key={c.id} className="inline-block mx-2">{c.label}: {c.phone}</span>)}
                    </div>
                    <div className="text-[10px] text-muted-foreground mt-2">
                        Generated by myshopbook.vercel.app
                    </div>
                </header>

                <div className="border-t pt-4 my-4 space-y-1">
                    <div className="flex justify-between items-center">
                        <div className="flex items-center gap-2">
                            <span className="font-semibold">Bill #: {bill.billNumber || 'Ref'}</span>
                            {bill.isEdited && !bill.hideEditedBadge && (
                                <span className="bg-amber-100 text-amber-800 text-[10px] font-bold px-1.5 py-0.5 rounded border border-amber-300">
                                    Edited / تبدیل شدہ
                                </span>
                            )}
                        </div>
                        <span>Date: {formatDateTime(bill.date)}</span>
                    </div>
                    <div className="flex flex-col">
                        <p>{partyLabel}: {bill.customerName}</p>
                        {customer?.phone && (
                            <p className="text-xs text-muted-foreground">Phone: {customer.phone}</p>
                        )}
                        {bill.createdByName && (
                            <div className="mt-1 inline-flex items-center gap-1.5 text-xs font-semibold text-[#6B7A50] bg-[#6B7A50]/10 px-2 py-0.5 rounded border border-[#6B7A50]/20 w-fit">
                                <span>🧑‍💼 Created by Staff: <strong>{bill.createdByName}</strong> {bill.createdByRole ? `(${bill.createdByRole})` : ''}</span>
                            </div>
                        )}
                    </div>
                </div>

                <div className="my-6">
                    <table className="w-full border-collapse">
                        <thead>
                            <tr className="border-y-2 border-[#6B7A50]">
                                <th className="text-left py-2 font-bold uppercase text-[11px] text-[#6B7A50]">Item</th>
                                <th className="text-center py-2 font-bold uppercase text-[11px] text-[#6B7A50]">Qty</th>
                                <th className="text-right py-2 font-bold uppercase text-[11px] text-[#6B7A50]">Price</th>
                                <th className="text-right py-2 font-bold uppercase text-[11px] text-[#6B7A50]">Total</th>
                            </tr>
                        </thead>
                        <tbody>
                            {(bill.items || []).map((item, index) => (
                                <Fragment key={item.itemId ? `${item.itemId}-${index}` : `${item.itemName}-${index}`}>
                                    <tr className="border-b border-[#6B7A50]/40">
                                        <td className="py-2">{item.itemName}</td>
                                        <td className="text-center py-2">{item.quantity}</td>
                                        <td className="text-right py-2">{item.unitPrice.toLocaleString()}</td>
                                        <td className="text-right py-2 font-medium">{(item.quantity * item.unitPrice).toLocaleString()}</td>
                                    </tr>
                                    {item.notes && item.notes.trim() && (
                                        <tr key={`${index}-notes`} className="border-b border-[#6B7A50]/20">
                                            <td colSpan={4} className="pb-1.5 pt-0 pl-3 text-[10px] italic text-gray-500">↳ {item.notes.trim()}</td>
                                        </tr>
                                    )}
                                </Fragment>
                            ))}
                        </tbody>
                    </table>
                </div>

                <div className="mt-4 text-right space-y-1">
                    <p className="text-sm text-gray-800 font-medium drop-shadow-sm">Items Total: <span className="text-black">{bill.totalAmount.toLocaleString()}</span></p>
                    {(bill.previousBalance || 0) !== 0 && (
                        <p className="text-sm text-gray-800 font-medium drop-shadow-sm">Previous Balance: <span className="text-black">{(bill.previousBalance || 0).toLocaleString()}</span></p>
                    )}
                    <p className="text-lg font-bold text-[#6B7A50]">Grand Total: {(bill.grandTotal || bill.totalAmount).toLocaleString()}</p>
                </div>

                {/* Payments Section */}
                {(bill.amountPaid > 0 || (bill.additionalPayments && bill.additionalPayments.length > 0)) && (
                    <div className="mt-6 border-t pt-4">
                        <h3 className="font-bold text-black mb-2 text-[12px] uppercase">Payments</h3>
                        <div className="space-y-1.5 text-sm text-black drop-shadow-sm">
                            {bill.amountPaid > 0 && (
                                <div className="flex justify-between items-center py-0.5">
                                    <span>
                                        Initial Payment on {formatDateTime(bill.date)}
                                        {bill.createdByName && (
                                            <span className="text-[11px] font-semibold text-[#6B7A50] ml-1.5">
                                                (Recv by: {bill.createdByName})
                                            </span>
                                        )}
                                    </span>
                                    <span className="font-medium">{bill.amountPaid.toLocaleString()}</span>
                                </div>
                            )}
                            {bill.additionalPayments?.map(p => (
                                <div key={p.id} className="flex justify-between items-center py-0.5">
                                    <span>
                                        Payment on {formatDateTime(p.date)}
                                        {p.createdByName && (
                                            <span className="text-[11px] font-semibold text-[#6B7A50] ml-1.5">
                                                (Recv by: {p.createdByName})
                                            </span>
                                        )}
                                        {p.notes ? ` (${p.notes})` : ''}
                                    </span>
                                    <div className="flex items-center gap-2">
                                        {p.image && onViewImage && (
                                            <button onClick={(e) => { e.stopPropagation(); onViewImage!(p.image!); }} className="text-orange-500 hover:text-orange-600 drop-shadow-md">
                                                <Camera className="h-4 w-4" />
                                            </button>
                                        )}
                                        <span className="font-medium">{p.amount.toLocaleString()}</span>
                                    </div>
                                </div>
                            ))}
                        </div>
                    </div>
                )}

                {/* Bill Adjustments History if Edited */}
                {!bill.hideEditedBadge && bill.billAdjustments && bill.billAdjustments.length > 0 && (
                    <div className="mt-4 p-2.5 rounded-lg bg-amber-50/80 border border-amber-200/80 text-xs text-amber-900">
                        <p className="font-bold mb-1 flex items-center gap-1">
                            <span>⚠️</span> Bill Adjustments / تبدیلیاں:
                        </p>
                        <div className="space-y-2">
                            {bill.billAdjustments.map((adj, i) => {
                                // For legacy adjustments where changes/itemsSummary wasn't stored, detect added item
                                let itemChanges = adj.changes;
                                if ((!itemChanges || itemChanges.length === 0) && !adj.itemsSummary && adj.difference > 0 && bill.items) {
                                    const match = bill.items.find(it => (it.quantity * it.unitPrice) === adj.difference);
                                    if (match) {
                                        itemChanges = [{
                                            type: 'added',
                                            itemName: match.itemName,
                                            description: `Qty: ${match.quantity} × Rs. ${match.unitPrice.toLocaleString()} = +Rs. ${adj.difference.toLocaleString()}`
                                        }];
                                    }
                                }

                                return (
                                    <div key={i} className="text-[11px] border-b border-amber-200/50 pb-2 last:border-b-0 last:pb-0">
                                        <div className="flex justify-between items-center">
                                            <span className="font-medium text-gray-800">
                                                {formatDateTime(adj.editedAt)} (Grand Total: {adj.previousGrandTotal?.toLocaleString()} → {adj.newGrandTotal?.toLocaleString()})
                                            </span>
                                            <span className={`font-semibold ${adj.difference > 0 ? 'text-green-700' : 'text-red-700'}`}>
                                                {adj.difference > 0 ? '+' : ''}{adj.difference.toLocaleString()}
                                            </span>
                                        </div>
                                        {itemChanges && itemChanges.length > 0 ? (
                                            <div className="mt-1 pl-2 space-y-0.5 text-[10px] bg-amber-100/40 p-1.5 rounded">
                                                {itemChanges.map((ch, idx) => (
                                                    <div key={idx} className="flex flex-wrap items-center gap-1">
                                                        {ch.type === 'added' && <span className="text-green-700 font-bold">➕ شامل کیا (Added):</span>}
                                                        {ch.type === 'removed' && <span className="text-red-700 font-bold">❌ حذف کیا (Removed):</span>}
                                                        {ch.type === 'modified' && <span className="text-blue-700 font-bold">🔄 تبدیل کیا (Changed):</span>}
                                                        <span className="font-semibold text-gray-900">{ch.itemName}</span>
                                                        <span className="text-gray-600">({ch.description})</span>
                                                    </div>
                                                ))}
                                            </div>
                                        ) : adj.itemsSummary ? (
                                            <div className="mt-1 pl-2 text-[10px] text-gray-700 whitespace-pre-line font-medium bg-amber-100/40 p-1.5 rounded">
                                                {adj.itemsSummary}
                                            </div>
                                        ) : null}
                                    </div>
                                );
                            })}
                        </div>
                    </div>
                )}

                <div className="mt-6 border-t pt-4 flex flex-col items-end space-y-1">
                    <div className="flex justify-between w-full max-w-[200px] text-green-600 font-semibold">
                        <span>Total Paid:</span>
                        <span>{totalPaid.toLocaleString()}</span>
                    </div>
                    <div className="flex justify-between w-full max-w-[200px] text-red-600 font-bold text-lg">
                        <span>Remaining Balance:</span>
                        <span>{finalBalance.toLocaleString()}</span>
                    </div>
                </div>

                {/* Account Managed by Footer */}


                {settings.footer && (
                    <div className="mt-2 text-center text-xs text-muted-foreground italic">
                        {settings.footer}
                    </div>
                )}
            </div>
        </div>
    );
};
